/**
 * Shared type definitions for the hooks layer.
 */

import type {ToolSessionContext} from './tools.ts';
import type {CommandSessionContext} from './commands.ts';
import type {GoalStateMachine} from './state-machine.ts';
import type {LoopPolicy} from './continuation-loop.ts';
import type {CompletionGateDeps} from './completion-gate-run.ts';
import type {
  DefaultGoalOptions,
  RuntimeState,
} from './session-state-manager.ts';
import type {VerifierAvailability} from './steering.ts';

export interface SessionApi {
  messages: (sessionID: string, opts?: {limit?: number}) => Promise<unknown[]>;
  promptAsync: (
    sessionID: string,
    input: {parts: unknown[]},
  ) => Promise<{error?: {name?: string}}>;
  abort?: (sessionID: string) => Promise<unknown>;
}

export interface HookDeps {
  getSessionContext: (sessionID: string) => SessionContext | undefined;
  getLoopPolicy: () => LoopPolicy;
  commandName: string;
  sessionApi: SessionApi;
  logError: (message: string, error?: unknown) => Promise<void>;
  runtime?: RuntimeState;
  defaultOpts?: Required<DefaultGoalOptions>;
  announceGoalDecision?: (sessionID: string, text: string) => Promise<void>;
  completionJudge?: JudgeRef | null;
  /** Dependencies for the verifier-centric completion gate. */
  completionGate?: CompletionGateDeps | null;
  /**
   * Capability level the runtime advertises prior to contract-specific verifier resolution.
   * `may-auto-detected` indicates discovery (e.g., test commands/Makefile) runs on completion.
   */
  verifierAvailability?: VerifierAvailability;
  /** @deprecated Use verifierAvailability instead. Kept for backwards compatibility. */
  verifierConfigured?: boolean;
  /** Host workspace directory used when a goal has not yet captured its CWD. */
  workspaceDirectory?: string;
  warnTurnsRemaining?: number;
  warnDurationMsRemaining?: number;
  /**
   * Whether to enable the synthetic-idle poller (needed on v1 hosts that omit idle events).
   * Can be disabled in tests to prevent background timers competing on the event loop.
   */
  idlePoller?: boolean;
  /** Polling interval for synthetic idle detection in milliseconds (default: 5000ms). */
  idlePollerIntervalMs?: number;
  /** Required quiet window before synthesizing an idle event in milliseconds (default: 10000ms). */
  idleQuietMs?: number;
  /** Grace period after an authentic host idle before polling synthesizes one in milliseconds (default: 30000ms). */
  idleGraceMs?: number;
  warnTokensRemaining?: number;
}

/**
 * Completion judge reference.
 * When provided alongside `completionGate`, the completion gate uses verifier-based
 * settlement; otherwise falls back to the legacy judge path.
 */
export interface JudgeRef {
  (ctx: {
    goal: import('./state-machine.ts').GoalState;
    sessionID: string;
    latestText: string;
  }): Promise<{
    approved: boolean;
    reason: string;
  }>;
}

export interface SessionContext
  extends ToolSessionContext, CommandSessionContext {
  autoPromote?: () => Promise<void>;
  /** Durable settlement receipts for tracking transitions. */
  beginSettlement?: (receipt: {
    goalId: string;
    sessionID: string;
    targetStatus: string;
    kind: string;
    revision: number;
    startedAt: number;
  }) => Promise<void>;
  completeSettlement?: (goalId: string) => Promise<void>;
  /** All active machines for the session, used in multi-goal execution. */
  listMachines?: () => GoalStateMachine[];
}

export interface PluginHooks {
  config?: (config: unknown) => Promise<void>;
  'chat.params'?: (input: {
    sessionID: string;
    agent?: string;
    model?: string;
  }) => Promise<void>;
  'chat.message'?: (
    input: {sessionID: string},
    output: {parts: unknown[]},
  ) => Promise<void>;
  'command.execute.before'?: (
    input: {sessionID?: string; command?: string; arguments?: string},
    output: {
      parts: unknown[];
    },
  ) => Promise<void>;
  'experimental.chat.system.transform'?: (
    input: {sessionID: string},
    output: {system: string[]},
  ) => Promise<void>;
  'experimental.compaction.autocontinue'?: (
    input: {sessionID?: string},
    output: {
      enabled?: boolean;
    },
  ) => Promise<void>;
  'experimental.session.compacting'?: (
    input: {sessionID: string},
    output: {parts: unknown[]},
  ) => Promise<void>;
  event?: (event: {
    type: string;
    sessionID?: string;
    id?: string;
    properties?: Record<string, unknown>;
  }) => Promise<void>;
  tool?: Record<string, unknown>;
  dispose?: () => Promise<void>;
}

/** Terminal event descriptor returned when settling a session. */
export interface TerminalEventInfo {
  sessionID: string;
  stopReason: string;
  detail: string;
}

/** Prefix for synthetic event IDs generated by the idle poller. */
export const POLL_EVENT_PREFIX = 'v1-poll-';
